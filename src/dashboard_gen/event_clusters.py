# ------------------------------------------------------------------ 4 查询接口
def clusters_of(basin, topic):
    """取某流域某议题的事件簇；无定义返回空表（调用方需自行判空）"""
    return list(CLUSTERS.get((basin, topic), []))


def cluster_names(basin):
    """某流域全部簇名（去重保序）—— 供图例与筛选项"""
    out = []
    for (b, _t), cl in CLUSTERS.items():
        if b != basin:
            continue
        for c in cl:
            if c[0] not in out:
                out.append(c[0])
    return out


_MAP_CACHE = {}


def word_cluster_map(basin, topic=None):
    """词 → 簇名。词云着色用。

    返回 (m, amb)：
        m   词 → 簇名（跨簇词取首次出现的簇）
        amb 跨簇词 → [全部所属簇]（实测仅「消费」），前端据此在悬停提示里如实标注
    结果按 (流域, 议题) 缓存 —— 常量表，不会变。
    """
    ck = (basin, topic)
    if ck in _MAP_CACHE:
        return _MAP_CACHE[ck]
    m, amb = {}, {}
    for (b, t), cl in CLUSTERS.items():
        if b != basin or (topic and t != topic):
            continue
        for name, words, _g, _c in cl:
            for w in words:
                if w in m and m[w] != name:
                    amb.setdefault(w, [m[w]])
                    if name not in amb[w]:
                        amb[w].append(name)
                else:
                    m[w] = name
    for k, v in amb.items():
        m[k] = v[0]
    _MAP_CACHE[ck] = (m, amb)
    return m, amb


def cluster_color(basin, name):
    """取簇色（同一簇名跨流域同色，便于两流域对照）"""
    for cl in CLUSTERS.values():
        for n, _w, _g, c in cl:
            if n == name:
                return c
    return OTHER_COLOR


def cluster_gloss(basin, name):
    """取该流域下该簇的释义（找不到返回空串）"""
    for (b, _t), cl in CLUSTERS.items():
        if b != basin:
            continue
        for n, _w, g, _c in cl:
            if n == name:
                return g
    return ''


def classify_word(basin, word, topic=None):
    """词的语义分层 —— 词云颜色与诊断表的唯一判据。

    返回 (kind, group)：
        ('event',   '簇名')        彩色，字号照频次
        ('concept', '议题概念词')   灰阶浅
        ('noise',   '公文套话' / '行政区划名' / '政治主体词')
        ('other',   '泛义实义词')
    """
    m, _amb = word_cluster_map(basin, topic)
    if word in m:
        return 'event', m[word]
    if word in CONCEPT_WORDS:
        return 'concept', '议题概念词'
    for label, words in NOISE_WORDS.items():
        if word in words:
            return 'noise', label
    return 'other', '泛义实义词'


def color_of_word(basin, word, topic=None):
    """词云用色：事件词取簇色，其余取层色"""
    kind, grp = classify_word(basin, word, topic)
    return cluster_color(basin, grp) if kind == 'event' else LAYER_COLOR.get(grp, OTHER_COLOR)


def merge_groups_of(basin, topic):
    """展开同义归并表为可查询形态（总量由数据脚本现算）"""
    return [dict(label=g['label'], words=list(g['words']), note=g['note'])
            for g in MERGE_GROUPS]


def all_match_words(basin, topic):
    """某流域某议题下所有需匹配的词（去重保序）"""
    out = []
    for _name, words, _g, _c in clusters_of(basin, topic):
        for w in words:
            if w not in out:
                out.append(w)
    return out
