# -*- coding: utf-8 -*-
"""词条释义库（常量表 · 零依赖 · 零 IO）

用途
    给词云里的每个高频词配一段**专业解释**，供 `_wordcloud.js` 的悬停提示与
    固定解释面板使用。解决"词云只给频次、不给含义"的问题。

与 event_clusters.py 的分工
    event_clusters.py 回答「这个词属于哪一层 / 哪个事件簇」，是**分类**判据；
    本文件回答「这个词是什么意思、在舆情语境里怎么读」，是**释义**表。
    两者都不写统计量 —— 篇数、占比、排名一律由 build_basin_data.py 现算。

设计原则（四条，改这个文件前先读）
    1. 只有常量，不连库、不读文件、不 import 项目内其它模块
       —— 与 event_clusters.py 同构，供构建脚本与前端共享。
    2. **释义必须能独立成立**：一句话说清「它是什么」，不写
       "这是本批次的重要话题" 这类放之四海皆准的空话。写不出准确释义的词，
       就不要写进表里 —— 前端会退回到「分层说明 + 统计口径」，不会编造。
    3. **不给情绪倾向**。释义只解释词义与制度背景；褒贬、传播力、风险等级
       一律由其他卡片按数据说话，不在词条释义里暗示。
    4. `note` 只在"这个词有特殊读法陷阱"时才写（配额偏置、需并档、
       分词歧义、同篇多次提及……），没有就留空，不凑字数。

字段
    def   词条释义（一句话，规范表述）
    field 所属领域，用于面板上的小标签
    note  读图提示 / 口径陷阱；可为空

前端消费方式
    build_unified_page.py 把本文件注入 window.WCGLOSS，_wordcloud.js 里
    `WC.explain()` 查表；查不到时按分层生成兜底解释，绝不返回空。
"""

